  /** 规范化品名：简繁归一 → 全角转半角 → 去首尾空格 → 合并连续空格 → 截断 30 */
  function normalizeName(name) {
    var s = String(name || '').trim();
    if (!s) return '';
    s = toHalfWidth(toSimplified(s));
    s = s.replace(/\s+/g, ' ').trim();
    if (s.length > 30) s = s.slice(0, 30);
    return s;
  }

  /** 返回某品类受控子类清单（未定义品类返回空数组） */
  function subCats(cat) {
    var c = PUBLISH_CATALOG[cat];
    return c ? c.subCats.slice() : [];
  }

  /** 返回某品类·某子类的品名联想库（无则空数组） */
  function nameHints(cat, sub) {
    var c = PUBLISH_CATALOG[cat];
    if (!c || !c.names) return [];
    return (c.names[sub] || []).slice();
  }

  /** 品名是否命中词库标准名（归一后精确比对） */
  function isStandardName(cat, sub, name) {
    var n = normalizeName(name);
    if (!n) return false;
    return nameHints(cat, sub).some(function (x) { return normalizeName(x) === n; });
  }

  /** 相似度去重提示：在（当前子类词库 + 全品类词库）中找最相近的标准名，返回 {hit, name, dist} */
  function similarName(cat, sub, name, maxDist) {
    var n = normalizeName(name);
    if (!n) return { hit: false };
    maxDist = (typeof maxDist === 'number') ? maxDist : 2;
    var pool = [];
    /* 先取当前子类词库 */
    pool = pool.concat(nameHints(cat, sub));
    /* 再补全品类（同品类其它子类） */
    var c = PUBLISH_CATALOG[cat];
    if (c && c.names) {
      Object.keys(c.names).forEach(function (k) {
        if (k !== sub) pool = pool.concat(c.names[k]);
      });
    }
    var best = null;
    pool.forEach(function (x) {
      var xn = normalizeName(x);
      if (!xn) return;
      if (xn === n) { best = { hit: true, name: x, dist: 0 }; return; }
      /* 包含关系（一长一短互为子串，长度差 ≤ 4）视为近似 */
      var contains = (xn.indexOf(n) !== -1 || n.indexOf(xn) !== -1) && Math.abs(xn.length - n.length) <= 4;
      var d = editDistance(xn, n);
      if (contains && d <= 4) d = Math.min(d, 2);
      if (d <= maxDist) {
        if (!best || d < best.dist) best = { hit: true, name: x, dist: d };
      }
    });
    return best || { hit: false };
  }

  /** 子类猜测：按品名词表关键词对给定文本匹配，返回受控子类；未命中返回 ''（未分类） */
  function guessSubCate(cat, text) {
    var c = PUBLISH_CATALOG[cat];
    if (!c || !c.guess) return '';
    var t = normalizeName(text);
    if (!t) return '';
    t = toSimplified(toHalfWidth(String(text || ''))).replace(/\s+/g, '');
    /* 按 subCats 顺序遍历，先命中先得 */
    for (var i = 0; i < c.subCats.length; i++) {
      var sub = c.subCats[i];
      var kws = c.guess[sub];
      if (!kws || !kws.length) continue;
      for (var j = 0; j < kws.length; j++) {
        if (t.indexOf(kws[j]) !== -1) return sub;
      }
    }
    return '';
  }

  /** 记录级猜测：输入 record（含 category/subType/title），返回 {subCate, matched} */
  function guessRecord(record) {
    var r = record || {};
    var cat = r.category || r.cat || '';
    var text = [r.subType || r.sub || '', r.title || ''].join(' ');
    var sub = guessSubCate(cat, text);
    return { subCate: sub, matched: !!sub };
  }

  /** 搜索页匹配辅助：item 是否命中某子类标签（受控值相等优先，兼容旧数据关键词包含） */
  function matchSubCate(item, label) {
    var itemSub = item.subCate || '';
    if (itemSub && itemSub === label) return true;
    /* 旧 5 子类别名兼容：item.subCate 为旧名时，按别名映射表命中当前筛选 label */
    if (itemSub && SUBCAT_ALIAS_MAP[itemSub]) {
      var hits = SUBCAT_ALIAS_MAP[itemSub].hits;
      if (hits && hits.indexOf(label) !== -1) return true;
    }
    /* 旧数据无 subCate：用品名/标题关键词包含判断 */
    var text = [item.subType || '', item.sub || '', item.title || ''].join(' ').replace(/\s+/g, '');
    var c = PUBLISH_CATALOG[item.category || item.cat || ''];
    if (c && c.guess && c.guess[label]) {
      return c.guess[label].some(function (k) { return text.indexOf(k) !== -1; });
    }
    return false;
  }

